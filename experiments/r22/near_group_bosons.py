"""Unique invertible boson for all four C2 x C4 + 8 near-group centers.

CLASSICAL INPUT (Rowell--Solomon--Zhang, arXiv:2305.09108):
For a near-group category of type G+|G| with non-degenerate symmetric
bicharacter <,>, an invertible center object a_g is a boson exactly when
2g=0 and <g,g>=1.  For G=C2 x C4, all four inequivalent near-group
categories have bicharacter

  <(x1,y1),(x2,y2)>
    = exp(2*pi*i*x1*x2/2) * exp(2*pi*i*m*y1*y2/4),

with m=+1 or -1 (Table 3).

COMPUTATIONAL-CLAIM:
For either sign of m, the three nontrivial order-two elements have self-pairing
(-1,+1,-1), in the order (1,0),(0,2),(1,2).  Thus the center of every one of
the four categories has exactly one nontrivial invertible boson, a_(0,2), and
hence exactly one Tannakian Rep(C2) generated by an invertible simple object.

The computation is exact over rational exponents; no floating-point phase
comparison is used.
"""

from __future__ import annotations

from fractions import Fraction
from typing import Dict, Tuple

G = tuple((x, y) for x in range(2) for y in range(4))
ZERO = (0, 0)
Elt = Tuple[int, int]

# Rowell--Solomon--Zhang Table 3: J^1,J^2,J^3,J^4 have m=+1,-1,+1,-1.
FOUR_CLASSES = {
    "J1_(2,4)": +1,
    "J2_(2,4)": -1,
    "J3_(2,4)": +1,
    "J4_(2,4)": -1,
}


def add(a: Elt, b: Elt) -> Elt:
    return ((a[0] + b[0]) % 2, (a[1] + b[1]) % 4)


def order_two_nonzero() -> Tuple[Elt, ...]:
    out = tuple(g for g in G if g != ZERO and add(g, g) == ZERO)
    assert set(out) == {(1, 0), (0, 2), (1, 2)}
    return out


def self_pair_exponent(g: Elt, m: int) -> Fraction:
    """r in Q/Z such that <g,g>=exp(2*pi*i*r)."""
    x, y = g
    return (Fraction(x * x, 2) + Fraction(m * y * y, 4)) % 1


def self_pair_sign(g: Elt, m: int) -> int:
    exponent = self_pair_exponent(g, m)
    if exponent == 0:
        return +1
    if exponent == Fraction(1, 2):
        return -1
    raise AssertionError((g, m, exponent))


def bosons_for_m(m: int) -> Tuple[Elt, ...]:
    return tuple(g for g in order_two_nonzero() if self_pair_sign(g, m) == +1)


def class_report() -> Dict[str, Dict[str, object]]:
    report = {}
    for name, m in FOUR_CLASSES.items():
        signs = {g: self_pair_sign(g, m) for g in order_two_nonzero()}
        bosons = bosons_for_m(m)
        assert signs[(1, 0)] == -1
        assert signs[(0, 2)] == +1
        assert signs[(1, 2)] == -1
        assert bosons == ((0, 2),)
        report[name] = {"m": m, "order2_self_pairing": signs, "unique_nontrivial_boson": bosons[0]}
    return report


def main() -> None:
    print("nontrivial order-two elements:", order_two_nonzero())
    for name, data in class_report().items():
        print(name)
        print("  m:", data["m"])
        print("  self-pairing:", data["order2_self_pairing"])
        print("  unique nontrivial boson:", data["unique_nontrivial_boson"])
    print("PASS: every C2 x C4 + 8 near-group center has a unique nontrivial invertible boson")


if __name__ == "__main__":
    main()
